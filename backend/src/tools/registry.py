import asyncio
import json
import logging
from typing import Any

from pydantic import ValidationError

from src.tools.base import ToolContext, ToolDefinition

logger = logging.getLogger(__name__)

DEFAULT_TOOL_TIMEOUT_SECONDS = 15.0
DEFAULT_MAX_OUTPUT_CHARS = 8_000


def _error(code: str, message: str) -> str:
    return json.dumps({"status": "error", "error": code, "message": message})


class ToolRegistry:
    """Allowlist of tools the model may call.

    The model only ever supplies a tool name and a JSON string; it is looked up in
    this dict and validated against the tool's Pydantic model. Nothing generated by
    the model is ever evaluated, and unknown names are refused.
    """

    def __init__(self, tools: list[ToolDefinition] | None = None) -> None:
        self._tools: dict[str, ToolDefinition] = {}
        for tool in tools or []:
            self.register(tool)

    def register(self, tool: ToolDefinition) -> None:
        if tool.name in self._tools:
            raise ValueError(f"Tool already registered: {tool.name}")
        self._tools[tool.name] = tool

    @property
    def names(self) -> list[str]:
        return list(self._tools)

    def openai_tools(self) -> list[dict[str, Any]]:
        return [tool.openai_schema() for tool in self._tools.values()]

    async def dispatch(
        self,
        name: str,
        raw_arguments: str,
        ctx: ToolContext,
        *,
        timeout_seconds: float = DEFAULT_TOOL_TIMEOUT_SECONDS,
        max_output_chars: int = DEFAULT_MAX_OUTPUT_CHARS,
    ) -> str:
        """Run one tool call and return a JSON string for the model. Never raises."""
        tool = self._tools.get(name)
        if tool is None:
            return _error("unknown_tool", f"No tool named '{name}' is available.")

        try:
            args = tool.args_model.model_validate_json(raw_arguments or "{}")
        except ValidationError as exc:
            # Field locations and messages only; input values are not echoed back.
            problems = "; ".join(
                f"{'.'.join(str(p) for p in e['loc'])}: {e['msg']}" for e in exc.errors()
            )
            return _error("invalid_arguments", problems)

        try:
            result = await asyncio.wait_for(tool.handler(args, ctx), timeout=timeout_seconds)
        except TimeoutError:
            logger.warning("Tool %s timed out", name)
            return _error("timeout", "The operation took too long. It may not have completed.")
        except Exception:
            logger.exception("Tool %s failed", name)
            return _error("internal_error", "The operation failed. It was not confirmed.")

        output = json.dumps(result, default=str)
        if len(output) > max_output_chars:
            return _error("output_too_large", "Result too large; narrow the request.")
        return output


def build_default_registry() -> ToolRegistry:
    # Imported here so adding a tool module is a one-line change in one place.
    from src.tools.appointments.tools import APPOINTMENT_TOOLS

    return ToolRegistry([*APPOINTMENT_TOOLS])


tool_registry = build_default_registry()
